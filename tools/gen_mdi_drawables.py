#!/usr/bin/env python3
"""Generate Android VectorDrawables from Material Design Icons SVGs (deterministic, re-runnable).

    python3 tools/gen_mdi_drawables.py <dir with the @mdi/svg *.svg files> [--check]

Reads the curated list from core/src/test/resources/icons_v1.json (the app's copy of portico-ha's
contract/icons_v1.json) and writes app/src/main/res/drawable/ic_mdi_<name with - as _>.xml for each.
Every MDI icon is one 24x24 <path d="...">, which maps 1:1 to a VectorDrawable <path android:pathData>.
The fill is opaque black; the app tints it at run time (the theme's text colour).

How to get the SVGs (once, any directory, default network):
    mkdir -p /tmp/mdi && cd /tmp/mdi && npm pack @mdi/svg@7.4.47 && tar -xzf mdi-svg-7.4.47.tgz
    python3 tools/gen_mdi_drawables.py /tmp/mdi/package/svg

Chrome icons: the few icons the app's own screen furniture uses (today the Home top line's menu button) are
NOT button icons and are NOT in icons_v1.json (that list is shared with the HA plugin's picker in another
repo). They are listed in CHROME below, mdi name -> drawable file name, and generated the same way.

--check writes nothing and exits 1 if any file would change (the same bytes every run).
Run with python3 -I or from another directory: this script only reads the paths it is given.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONTRACT = ROOT / "core/src/test/resources/icons_v1.json"
OUT = ROOT / "app/src/main/res/drawable"
SVG = re.compile(r'^<svg[^>]*viewBox="0 0 24 24"[^>]*><path d="([^"]+)"\s*/></svg>\s*$')
# Chrome icons (see the docstring): mdi name -> drawable file name (no .xml). Not button icons; keep out of icons_v1.json.
CHROME = {"menu": "ic_menu_hamburger"}
NAME = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")

TEMPLATE = """<?xml version="1.0" encoding="utf-8"?>
<!-- Material Design Icons "{name}" (Apache-2.0, see third_party/mdi/NOTICE). Generated by tools/gen_mdi_drawables.py; do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="24"
    android:viewportHeight="24">
    <path
        android:fillColor="#FF000000"
        android:pathData="{path}" />
</vector>
"""


def main() -> int:
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    check = "--check" in sys.argv
    if len(args) != 1:
        print(__doc__)
        return 2
    svg_dir = Path(args[0])
    names = json.loads(CONTRACT.read_text())["icons"]
    changed = 0
    for name in names:
        if not NAME.match(name):
            raise SystemExit(f"bad icon name {name!r}")
        m = SVG.match((svg_dir / f"{name}.svg").read_text())
        if not m:
            raise SystemExit(f"{name}.svg is not a single 24x24 path")
        text = TEMPLATE.format(name=name, path=m.group(1))
        target = OUT / f"ic_mdi_{name.replace('-', '_')}.xml"
        if not target.is_file() or target.read_text() != text:
            changed += 1
            if not check:
                target.write_text(text)
    for name, file in CHROME.items():
        if not NAME.match(name):
            raise SystemExit(f"bad icon name {name!r}")
        m = SVG.match((svg_dir / f"{name}.svg").read_text())
        if not m:
            raise SystemExit(f"{name}.svg is not a single 24x24 path")
        text = TEMPLATE.format(name=name, path=m.group(1))
        target = OUT / f"{file}.xml"
        if not target.is_file() or target.read_text() != text:
            changed += 1
            if not check:
                target.write_text(text)
    print(f"{len(names)} icons + {len(CHROME)} chrome, {changed} {'would change' if check else 'written'}")
    return 1 if (check and changed) else 0


if __name__ == "__main__":
    sys.exit(main())
